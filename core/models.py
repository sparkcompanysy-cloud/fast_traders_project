import secrets
import string
from decimal import Decimal
from django.db import models
from django.contrib.auth.models import AbstractUser


class PlatformSetting(models.Model):
    """Stores global platform settings controlled by the Admin."""
    deposit_wallet_trc20 = models.CharField(
        max_length=255,
        default='TXYZabc123456789FastTradersSecureWallet'
    )
    deposit_wallet_bep20 = models.CharField(
        max_length=255,
        default='0xFastTradersBEP20SecureWalletAddress12345'
    )
    updated_at = models.DateTimeField(auto_now=True)

    @classmethod
    def get_solo(cls):
        obj, _ = cls.objects.get_or_create(pk=1)
        return obj

    def __str__(self):
        return f"Platform Settings (TRC20: {self.deposit_wallet_trc20})"


class User(AbstractUser):
    """Custom Trader & Admin User Model."""
    CAP_TYPE_CHOICES = [
        ('fixed', 'مبلغ ثابت بالدولار ($)'),
        ('percent', 'نسبة مئوية من إجمالي الإيداع (%)'),
    ]
    RISK_MODE_CHOICES = [
        ('capped', 'تفعيل سقف الربح والتعويض التلقائي'),
        ('house_edge', 'خسارة دائمة لجميع الضربات (House Edge)'),
        ('standard', 'تداول عشوائي مفتوح بدون سقف'),
    ]
    KYC_STATUS_CHOICES = [
        ('unverified', 'غير موثق (Tier 1)'),
        ('pending', 'قيد مراجعة الإدارة'),
        ('approved', 'حساب موثق بالكامل (Tier 2)'),
        ('rejected', 'مرفوض'),
    ]

    full_name = models.CharField(max_length=150, blank=True)
    email = models.EmailField(unique=True)
    activation_code = models.CharField(max_length=6, blank=True)

    # Financial Balances
    real_balance = models.DecimalField(max_digits=14, decimal_places=2, default=Decimal('0.00'))
    demo_balance = models.DecimalField(max_digits=14, decimal_places=2, default=Decimal('10000.00'))
    total_deposited = models.DecimalField(max_digits=14, decimal_places=2, default=Decimal('0.00'))
    daily_profit = models.DecimalField(max_digits=14, decimal_places=2, default=Decimal('0.00'))

    # Admin Profit Cap Modulator & Risk Controls
    profit_cap = models.DecimalField(max_digits=14, decimal_places=2, default=Decimal('20.00'))
    cap_type = models.CharField(max_length=16, choices=CAP_TYPE_CHOICES, default='fixed')
    risk_mode = models.CharField(max_length=20, choices=RISK_MODE_CHOICES, default='capped')

    # KYC & Account Status
    kyc_status = models.CharField(max_length=20, choices=KYC_STATUS_CHOICES, default='unverified')
    is_banned = models.BooleanField(default=False)

    @property
    def display_name(self):
        return self.full_name or self.username

    @property
    def effective_profit_cap(self):
        if self.cap_type == 'percent':
            return (self.total_deposited * self.profit_cap) / Decimal('100.00')
        return self.profit_cap

    def __str__(self):
        return f"#{self.id} - {self.display_name} ({self.email})"


class ActivationCode(models.Model):
    """Single-use 6-character activation codes generated by the Admin."""
    code = models.CharField(max_length=6, unique=True, db_index=True)
    is_used = models.BooleanField(default=False)
    used_by = models.OneToOneField(
        User,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='used_code_record'
    )
    created_at = models.DateTimeField(auto_now_add=True)
    used_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        ordering = ['is_used', '-created_at']

    @classmethod
    def generate_codes(cls, quantity=1):
        """
        Generates `quantity` unique 6-character uppercase codes (ABC...Z + 0-9).
        If you want strictly letters A-Z only, change alphabet to: string.ascii_uppercase
        """
        quantity = max(1, min(int(quantity), 500))  # Safety limit: 1 to 500 per batch
        alphabet = string.ascii_uppercase + string.digits
        created_codes = []

        while len(created_codes) < quantity:
            candidate = ''.join(secrets.choice(alphabet) for _ in range(6))
            if not cls.objects.filter(code=candidate).exists():
                obj = cls.objects.create(code=candidate)
                created_codes.append(obj)

        return created_codes

    def __str__(self):
        status = f"Used by #{self.used_by_id}" if self.is_used else "Unused (Available)"
        return f"{self.code} - {status}"


class KYCDocument(models.Model):
    """Stores identity verification details and uploaded ID images."""
    user = models.OneToOneField(User, on_delete=models.CASCADE, related_name='kyc_data')
    full_name = models.CharField(max_length=150)
    dob = models.DateField()
    address = models.CharField(max_length=255)
    doc_number = models.CharField(max_length=100)
    front_id_img = models.ImageField(upload_to='kyc/front/')
    back_id_img = models.ImageField(upload_to='kyc/back/')
    submitted_at = models.DateTimeField(auto_now=True)

    def __str__(self):
        return f"KYC for #{self.user.id} ({self.full_name})"


class Asset(models.Model):
    """Trading pairs/markets controlled by the Admin."""
    CATEGORY_CHOICES = [
        ('فوركس', 'فوركس'),
        ('عملات رقمية', 'عملات رقمية'),
        ('معادن', 'معادن'),
        ('أسهم', 'أسهم'),
    ]

    symbol = models.CharField(max_length=30, unique=True)
    name = models.CharField(max_length=100)
    category = models.CharField(max_length=50, choices=CATEGORY_CHOICES, default='فوركس')
    payout = models.PositiveIntegerField(default=90)
    min_deposit = models.DecimalField(max_digits=12, decimal_places=2, default=Decimal('100.00'))
    base_price = models.DecimalField(max_digits=16, decimal_places=5, default=Decimal('1.08450'))
    locked_by_admin = models.BooleanField(default=False)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['id']

    def __str__(self):
        return f"{self.symbol} (+{self.payout}%)"


class Transaction(models.Model):
    """Deposits (with receipt images) and Withdrawals (with wallet addresses)."""
    TX_TYPE_CHOICES = [
        ('إيداع', 'إيداع'),
        ('سحب', 'سحب'),
    ]
    STATUS_CHOICES = [
        ('قيد المراجعة', 'قيد المراجعة'),
        ('مكتمل', 'مكتمل'),
        ('مرفوض', 'مرفوض'),
    ]

    user = models.ForeignKey(User, on_delete=models.CASCADE, related_name='transactions')
    tx_type = models.CharField(max_length=20, choices=TX_TYPE_CHOICES)
    network = models.CharField(max_length=50, default='TRC20')
    amount = models.DecimalField(max_digits=14, decimal_places=2)
    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default='قيد المراجعة')
    proof_image = models.ImageField(upload_to='receipts/', null=True, blank=True)
    wallet_address = models.CharField(max_length=255, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['-created_at']

    def __str__(self):
        return f"{self.tx_type} ${self.amount} - {self.user.display_name} ({self.status})"


class Trade(models.Model):
    """Stores live binary option trades executed on the terminal."""
    DIRECTION_CHOICES = [
        ('CALL', 'صعود / CALL'),
        ('PUT', 'هبوط / PUT'),
    ]
    ACCOUNT_CHOICES = [
        ('real', 'Real'),
        ('demo', 'Demo'),
    ]

    user = models.ForeignKey(User, on_delete=models.CASCADE, related_name='trades')
    asset = models.ForeignKey(Asset, on_delete=models.SET_NULL, null=True, blank=True)
    symbol = models.CharField(max_length=30)
    account_type = models.CharField(max_length=10, choices=ACCOUNT_CHOICES, default='real')
    direction = models.CharField(max_length=10, choices=DIRECTION_CHOICES)
    amount = models.DecimalField(max_digits=14, decimal_places=2)
    duration = models.PositiveIntegerField(default=3)
    is_win = models.BooleanField(default=False)
    result_amount = models.DecimalField(max_digits=14, decimal_places=2)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['-created_at']

    def __str__(self):
        return f"{self.user.display_name} | {self.symbol} {self.direction} ${self.amount}"
